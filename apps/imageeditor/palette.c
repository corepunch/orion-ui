/* Disney Animation Studio DOS palette reference and app default.
 * RGB components retain their source precision and palette index order.
 * Convert a 6-bit component to 8-bit with (value * 255 + 31) / 63.
 * Index maps address ip_ega_master. IP adjusts brown for the adapter:
 * slot 5 switches between indices 20 and 6, and entry 6 green between
 * 42 and 21 (IP.EXE file offsets 0x1d83c..0x1d858). Tables below are raw.
 * The CFT pair records header triplets; it is not an IP preset.
 * Screenshot colors are JPEG samples converted through its embedded profile
 * to sRGB; white is assumed. They are not verified DOS palette values.
 * disney_extended_32 is the app default: the Disney screenshot-based 16
 * followed by 16 proposed additions. Black and white occupy slots 0 and 1
 * for the app's ink/paper contract. The additions are not Disney artwork.
 */
