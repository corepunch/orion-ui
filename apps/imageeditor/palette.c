#include <stdint.h>
#include "palette.h"

typedef struct {
  const char *name;
  const char *source;
  uint32_t source_offset;
  uint16_t count;
  uint8_t component_bits;
  const uint8_t (*rgb)[3];
} das_rgb_palette_t;

typedef struct {
  const char *name;
  const char *source;
  uint32_t source_offset;
  uint16_t count;
  const uint8_t *indices;
} das_index_palette_t;

