local Hotel = require("hotel")
local orion = require("orion")
local room = orion.assert(Hotel.rooms:save(nil, {name = "101", category = "Double", capacity = 2, rate = 99.95}))
local guest = orion.assert(Hotel.guests:save(nil, {name = 'Ada <Example>', phone = "123"}))
assert(not Hotel.rooms:save(nil, {name = "", capacity = 2, rate = 10}))
assert(not Hotel.rooms:save(nil, {name = "Bad", capacity = 0, rate = 10}))
local function fields(a, d)
  return {room_id = room.id, guest_id = guest.id, arrival = a, departure = d, persons = 2, rate = 99.95, extras = 10, paid = 50, notes = ""}
end
local booking = orion.assert(Hotel.save(nil, fields("2026-03-28", "2026-03-30")))
assert(Hotel.total(booking) == 209.9 and Hotel.balance(booking) == 159.9)
assert(not Hotel.save(nil, fields("2026-03-29", "2026-03-31")))
assert(not Hotel.save(nil, fields("2026-03-30", "2026-03-30")))
assert(not Hotel.save(nil, fields("2026-02-29", "2026-03-01")))
local overcapacity = fields("2026-04-01", "2026-04-02"); overcapacity.persons = 3
assert(not Hotel.save(nil, overcapacity))
assert(not Hotel.rooms:delete(room.id))
assert(not Hotel.guests:delete(guest.id))
local nextBooking = orion.assert(Hotel.save(nil, fields("2026-03-30", "2026-03-31")))
orion.assert(Hotel.transition(nextBooking.id, "cancelled"))
orion.assert(Hotel.save(nil, fields("2026-03-30", "2026-03-31")))
assert(not Hotel.transition(nextBooking.id, "checked_in"))
orion.assert(Hotel.transition(booking.id, "checked_in"))
assert(not Hotel.transition(booking.id, "checked_out"))
local settled = fields("2026-03-28", "2026-03-30"); settled.paid = 209.9
orion.assert(Hotel.save(booking.id, settled))
orion.assert(Hotel.transition(booking.id, "checked_out"))
assert(not Hotel.save(booking.id, settled))
assert(not Hotel.save(9999, settled))
