#!/usr/bin/env python3
"""Turn a Kenney colormap.png into gradient swatches for Scener.

Kenney's kits are textured from one colormap: columns 32 px wide, each a vertical gradient (light at the
top, dark below) that a model's faces are mapped across by height. Each swatch becomes a gradient colour,
a bottom and a top colour, that Scener draws with gradientFrom/gradientTo over the shape's height.

    kenney_palette.py colormap.png --name fantasy_town --blks palette.xml --lua palette.lua --py palette.py

--blks   <material> elements for a .blks (paste inside <scene>, or into a prefab), used as material="id"
--lua    a Lua module:   return { fantasy_town_c00_b1 = {bottom = {r,g,b}, top = {r,g,b}}, ... }
--py     a Python module: PALETTE = {"fantasy_town_c00_b1": ((r,g,b), (r,g,b)), ...}  (bottom, top)
--span   the part of a swatch's height the colours are taken from (default 0.3 0.7, the part Kenney's own
         wall faces map to; 0 1 uses the full swatch)
Colours are sRGB 0..1, as scene files expect.
"""
import argparse, sys
from PIL import Image

STRIP, JUMP, MIN_RUN, EDGE = 32, 24, 16, 2   # strip width, row-to-row colour jump that ends a swatch, shortest swatch, rows ignored at a swatch's ends


def swatches(path):
  im = Image.open(path).convert("RGBA")
  px, (w, h) = im.load(), im.size
  out = []
  for col in range(w // STRIP):
    x = col * STRIP + STRIP // 2
    runs, start = [], None
    for y in range(h + 1):
      cur = px[x, y][:3] if y < h and px[x, y][3] > 0 else None
      if cur is not None and cur == (0, 0, 0): cur = None
      if start is not None and (cur is None or max(abs(a - b) for a, b in zip(cur, px[x, y - 1][:3])) > JUMP):
        runs.append((start, y)); start = None
      if start is None and cur is not None: start = y
    for y0, y1 in runs:
      if y1 - y0 >= MIN_RUN: out.append((col, y0, y1, [px[x, y][:3] for y in range(y0, y1)]))
  return out


def at(rows, f):
  i = f * (len(rows) - 1)
  lo = int(i); hi = min(lo + 1, len(rows) - 1); t = i - lo
  return tuple((rows[lo][k] * (1 - t) + rows[hi][k] * t) / 255 for k in range(3))


def build(path, name, span):
  items = []
  for col, y0, y1, rows in swatches(path):
    rows = rows[EDGE:-EDGE] or rows
    top, bottom = at(rows, span[0]), at(rows, span[1])   # image rows run top to bottom, models map height upwards
    items.append(("%s_c%02d_b%d" % (name, col, y0 // 128), bottom, top))
  return items


def rgb(c): return " ".join("%.3f" % v for v in c)


def main():
  ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
  ap.add_argument("colormap"); ap.add_argument("--name", required=True)
  ap.add_argument("--blks"); ap.add_argument("--lua"); ap.add_argument("--py")
  ap.add_argument("--span", nargs=2, type=float, default=[.3, .7])
  a = ap.parse_args()
  items = build(a.colormap, a.name, a.span)
  if not items: sys.exit("no swatches found in " + a.colormap)
  if a.blks:
    with open(a.blks, "w") as f:
      f.write("<!-- Gradient swatches from %s (Kenney, CC0); bottom -> top along y. Generated by tools/kenney_palette.py -->\n" % a.colormap.split("/")[-1])
      for i, b, t in items:
        f.write('<material id="%s" color="1 1 1" gradientFrom="%s" gradientTo="%s" shininess="6"/>\n' % (i, rgb(b), rgb(t)))
  if a.lua:
    with open(a.lua, "w") as f:
      f.write("-- Gradient swatches from %s (Kenney, CC0). Generated by tools/kenney_palette.py\nreturn {\n" % a.colormap.split("/")[-1])
      for i, b, t in items: f.write("  %s = {bottom = {%s}, top = {%s}},\n" % (i, ", ".join("%.3f" % v for v in b), ", ".join("%.3f" % v for v in t)))
      f.write("}\n")
  if a.py:
    with open(a.py, "w") as f:
      f.write('"""Gradient swatches from %s (Kenney, CC0): name -> (bottom, top) sRGB. Generated by tools/kenney_palette.py"""\nPALETTE = {\n' % a.colormap.split("/")[-1])
      for i, b, t in items: f.write('  "%s": ((%s), (%s)),\n' % (i, ", ".join("%.3f" % v for v in b), ", ".join("%.3f" % v for v in t)))
      f.write("}\n")
  print("%d swatches from %s" % (len(items), a.colormap))


main()
