local A = assert(ledger.automation, "automation bootstrap must load")
local function fails(fn, fragment)
  local ok, err = pcall(fn)
  assert(not ok, "expected failure")
  if fragment then assert(tostring(err):find(fragment, 1, true), tostring(err)) end
end
local function approx(a, b) assert(math.abs(a - b) < 0.00001, tostring(a) .. " ~= " .. tostring(b)) end
