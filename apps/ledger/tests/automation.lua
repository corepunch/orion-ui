  {id="plan",type="plan.upsert",input="mapped",params={table="items",keys={"sku"}}},
  {id="text",type="source.text",params={text="Code;Title;Price\nGRAPH;Graph item;25\n"}},
  {id="csv",type="parse.csv",input="text"},
  {id="mapped",type="rows.map",input="csv",params={columns={Code="sku",Title="name",Price="price"},types={price="number"}}},
