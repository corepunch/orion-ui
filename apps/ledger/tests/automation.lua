local function run_node(typ, params, input)
  return A.execute({nodes={{id="rows",type="source.rows",params={rows=input}},{id="result",type=typ,input="rows",params=params}},output="result"})
end
assert(#A.execute({nodes={{id="items",type="source.table",params={table="items"}}},output="items"}) == count("items"))
assert(#run_node("rows.filter",{equals={x=1}},{{x=1},{x=2}}) == 1)
assert(run_node("rows.group",{keys={"x"},sum="v"},{{x="a",v=2},{x="a",v=3}})[1].total == 5)
assert(#run_node("check.required",{fields={"x"}},{{x=""}}) == 1)
assert(#run_node("rows.match",{table="items",keys={"sku"}},{{sku="GRAPH"}}) == 1)
assert(#run_node("check.duplicates",{keys={"x"}},{{id=1,x="a"},{id=2,x="a"}}) == 1)
assert(#run_node("plan.patch",{table="items",field="name",value="Graph changed"},ledger.fetch("ib","items","sku","GRAPH")).changes == 1)
