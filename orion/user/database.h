#ifndef __UI_DATABASE_H__
#define __UI_DATABASE_H__

#include <stddef.h>
#include <stdint.h>
#include <stdbool.h>

// Forward declarations
typedef struct database_s database_t;
typedef intptr_t lresult_t;  // Pointer-sized result (like WinAPI LRESULT)

// Database procedure callback type (analogous to winproc_t)
typedef lresult_t (*dbproc_t)(database_t *, uint32_t, uint32_t, void *);

// Database messages
enum {
  dbCreate,          // wparam=0; lparam=const char* source_path → returns 1 on success
  dbDestroy,         // cleanup → returns 1 on success
  dbLoad,            // load from source → returns 1 on success
  dbSave,            // save to source (only if dirty) → returns 1 on success
  dbInsert,          // wparam=table_id; lparam=record_data → returns (lresult_t)record_ptr
  dbUpdate,          // wparam=table_id; lparam=record_data → returns 1 on success
  dbDelete,          // wparam=table_id; lparam=(void*)(intptr_t)record_id → returns 1 on success
  dbFetch,           // wparam=MAKEDWORD(table_id,filter_field); lparam=(intptr_t)filter_value → returns (lresult_t)result_node_t* (linked list)
  dbFind,            // wparam=MAKEDWORD(table_id,search_field); lparam=(intptr_t)value or (void*)str → returns (lresult_t)record_ptr
  dbGetDirty,        // returns dirty flag as lresult_t (0 or 1)
  dbGetObjectProc,   // wparam=table_id; lparam=0 → returns (lresult_t)db_object_proc_t
  dbGetFieldBindings, // wparam=table_id; lparam=int* count_out → returns (lresult_t)db_field_msg_binding_t*
  dbGetSchema,       // wparam=0; lparam=0 → returns (lresult_t)const db_schema_def_t*
  dbGetFieldMeta,    // wparam=table_id; lparam=int* count_out → returns (lresult_t)const db_field_meta_t*
  dbGetApi,          // wparam=0; lparam=0 → returns (lresult_t)const db_api_def_t*
  dbGetFieldText,    // wparam=table_id; lparam=db_field_text_t* → returns 1 when formatted
  // Record lifecycle, after NeXTSTEP DBKit and EOF (Enterprise Objects):
  dbInitRecord,      // wparam=table_id; lparam=record buffer → fills a new record's defaults (awakeFromInsertion)
  dbCountReferrers,  // wparam=table_id; lparam=(intptr_t)id → records whose delete rule denies deleting it
  dbBeginChanges,    // opens a nested change scope (editing context) → returns 1 when supported
  dbCommitChanges,   // keeps the changes of the innermost scope
  dbRevertChanges,   // undoes every change of the innermost scope
  dbReserveKey,      // reserves a stable integer key without inserting a record
  dbCreateEditContext, // creates an independent working copy, when supported
  dbUser = 1000      // custom database implementations can use dbUser+
};

// Result node for dbFetch (linked list of records)
// Caller must free with free_result_list() after use
typedef struct result_node_s {
  void *next;              // Next node (NULL for last)
  char data[];             // Flexible array member - record data
} result_node_t;

// Field types for reflection-based XML loading
typedef enum {
  DB_TYPE_INT,
  DB_TYPE_STRING,
  DB_TYPE_BOOL,
  DB_TYPE_FLOAT,
  DB_TYPE_DOUBLE,
  DB_TYPE_DATE     // char[11] "YYYY-MM-DD"; displayed in the catalog's date format
} db_field_type_t;

// Field metadata for reflection (generated by orionc from <table> schemas)
typedef struct {
  const char *name;        // Field name (e.g., "author_id")
  db_field_type_t type;    // C type
  size_t offset;           // offsetof(struct_t, field)
  int length;              // For strings: buffer size; else 0
  int precision;           // Display decimals for float/double (0 = 2)
} db_field_meta_t;

// What deleting a referenced record does to the records referring to it,
// as EOF's delete rules: nothing, delete them too, clear the reference, or
// refuse the delete while they exist.
typedef enum { DB_DELETE_NO_ACTION, DB_DELETE_CASCADE, DB_DELETE_NULLIFY, DB_DELETE_DENY } db_delete_rule_t;

// Design-time schema metadata for editor/database browsers.
typedef struct {
  const char *name;            // Field name (e.g., "author_id")
  db_field_type_t type;        // Field type
  int length;                  // String buffer size; else 0
  bool primary_key;            // true for key fields
  const char *relation_table;  // Foreign table, if this field references one
  const char *relation_field;  // Foreign field, if this field references one
  const char *default_value;   // Value of a new record (dbInitRecord); "today" for dates
  db_delete_rule_t delete_rule; // Applied to this record when the referenced one is deleted
} db_field_schema_t;

typedef struct {
  const char *name;          // Join alias (e.g., "author")
  const char *local_field;   // Local FK field (e.g., "author_id")
  const char *foreign_table; // Referenced table (e.g., "authors")
  const char *foreign_field; // Referenced field (e.g., "id")
} db_join_schema_t;

typedef struct {
  int table_id;                         // TABLE_* value
  const char *name;                     // Table name (e.g., "posts")
  const char *model;                    // Optional logical model name
  const db_field_schema_t *fields;
  int field_count;
  const db_join_schema_t *joins;
  int join_count;
  size_t record_size;                   // sizeof the generated record struct
  const db_field_meta_t *meta;          // Field offsets for reflection
  int meta_count;
  bool transient;                       // derived data: never saved, never dirties the database
} db_table_schema_t;

typedef struct {
  const char *name;                     // Database instance name
  const char *class_name;               // Database class/proc name
  const char *source_path;              // Backing source, if any
  const db_table_schema_t *tables;
  int table_count;
} db_schema_def_t;

// Database class descriptor
typedef struct {
  const char *class_name;  // "SimpleXMLDatabase", etc.
  dbproc_t proc;           // database procedure
} db_class_desc_t;

// dbGetFieldText payload. field may be a join path such as "author.name".
typedef struct {
  const void *record;
  const char *field;
  char *buf;
  size_t buf_sz;
} db_field_text_t;

// Database structure (analogous to window_t)
struct database_s {
  const char *name;        // database instance name
  const char *class_name;  // registered class name
  dbproc_t proc;           // database procedure
  void *userdata;          // implementation-specific data
  char source_path[512];   // path to XML/SQLite/etc. file
  bool dirty;              // needs save
  const db_schema_def_t *schema; // declared schema (generated by orionc), if any
  database_t *edit_parent; // private document working copy; NULL for a committed store
  unsigned message_refs;
  bool destroy_pending;
};

// Database management functions
database_t *create_database(const char *name, const char *class_name, const char *source_path);
// Like create_database, but attaches the orionc-generated schema before
// dbCreate/dbLoad so schema-driven classes (db_schema_xml) can use it.
database_t *create_database_with_schema(const char *name, const char *class_name,
                                        const db_schema_def_t *schema,
                                        const char *source_path);
void destroy_database(database_t *db);
lresult_t send_db_message(database_t *db, uint32_t msg, uint32_t wparam, void *lparam);
// Independent document working copies. Commit applies only this editor's delta,
// atomically, after checking changed records against their original versions.
// The parent must outlive the context. Reset or destroy after a successful save;
// reset preserves the database handle but invalidates its record pointers.
database_t *db_edit_context_create(database_t *store);
bool db_edit_context_save(database_t *context, char *error, size_t error_size);
bool db_edit_context_reset(database_t *context);
// The clean checkpoint tracks user edits after draft/default initialization;
// it does not replace the parent baseline used to save or detect conflicts.
bool db_edit_context_mark_clean(database_t *context);
bool db_edit_context_has_changes(database_t *context);
database_t *db_set_message_context(database_t *context); // returns the previous UI-message context
void db_message_retain(database_t *context);
void db_message_release(database_t *context);

// Schema helpers
const db_table_schema_t *db_schema_table(const db_schema_def_t *schema, int table_id);
const db_table_schema_t *db_schema_table_named(const db_schema_def_t *schema, const char *name);
int db_schema_field_index(const db_table_schema_t *table, const char *field);
bool db_format_field(const db_field_meta_t *field, const void *record, char *buf, size_t buf_sz);
bool db_record_equal(const db_field_meta_t *fields, int count, const void *a, const void *b);
// Sets a field from text as it is stored ("12.5", "2003-03-31", "1"); "today"
// sets a date field to the current date.
bool db_parse_field(const db_field_meta_t *field, void *record, const char *text);
// Formats a field (or join path "author.name") using the table schema.
// Joins resolve through dbFind on the related database ("db.table" relations
// name another registered database). A polymorphic relation takes its table
// name from a path on the same record: "ib.{debit.subconto_kind.table}".
bool db_schema_field_text(database_t *db, const db_table_schema_t *table,
                          const void *record, const char *field,
                          char *buf, size_t buf_sz);
// The type of a field or join path ("item.price") of a schema table, or -1
// when it cannot be resolved (unknown field, polymorphic relation).
int db_schema_field_type(database_t *db, const db_table_schema_t *table, const char *field);
// The metadata (type, display precision) of the same field or join path, or NULL.
const db_field_meta_t *db_schema_field_meta(database_t *db, const db_table_schema_t *table, const char *field);
// Formats a record field for display: dbGetFieldText when the database
// implements it, otherwise the table's object proc and field bindings.
bool db_get_field_text(database_t *db, int table_id, const void *record,
                       const char *field, char *buf, size_t buf_sz);

// Schema-driven XML database class: CRUD, fetch, find and joins from the
// generated schema alone. Register with DB_CLASS(db_schema_xml) and create
// with create_database_with_schema().
lresult_t db_schema_xml(database_t *db, uint32_t msg, uint32_t wparam, void *lparam);

// Result list helpers
void free_result_list(void *head);
int count_result_list(void *head);

// Reflection-based XML loading (uses generated field metadata from orionc)
// These helpers are available to all database implementations
#include <libxml/tree.h>
bool db_load_field_from_xml(xmlNodePtr node, void *record_base,
                             const db_field_meta_t *field);
bool db_load_record_from_xml(xmlNodePtr node, void *record,
                              const db_field_meta_t *fields, int field_count);

// Reflection-based XML saving (uses generated field metadata from orionc)
bool db_save_field_to_xml(xmlNodePtr node, const void *record_base,
                           const db_field_meta_t *field);
xmlNodePtr db_save_record_to_xml(xmlNodePtr parent, const char *element_name,
                                  const void *record, const db_field_meta_t *fields,
                                  int field_count);

// Database class registry
bool register_database_class(const db_class_desc_t *desc);
dbproc_t find_database_class_proc(const char *class_name);

// Database instance registry (for declarative forms)
// Forms with field="db.table.field" look up the database by name automatically
bool register_database(const char *name, database_t *db);
database_t *get_database_by_name(const char *name);
// Removes a name from the registry (the database itself stays); false when absent.
bool unregister_database(const char *name);
// The index-th registered database, in registration order, or NULL past the end.
database_t *get_database_at(int index);

#define DB_CLASS(proc_sym) \
  register_database_class(&(db_class_desc_t){ .class_name = #proc_sym, .proc = (proc_sym) })

#endif // __UI_DATABASE_H__
