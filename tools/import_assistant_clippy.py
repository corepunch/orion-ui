#!/usr/bin/env python3
"""Build the prototype's Clippy atlases from a local codex-clippy extraction.

Usage: python tools/import_assistant_clippy.py /path/to/codex-clippy
Writes assets/clippy and animations.lua. No download is performed.
"""
import argparse
import json
import io
import os
from pathlib import Path
from PIL import Image

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('source',type=Path)
    a=p.parse_args()
    target=Path(__file__).resolve().parents[1]/'apps/ledger/share/addons/assistant'
    output=target/'assets/clippy'
    output.mkdir(parents=True,exist_ok=True)
    manifest=json.loads((a.source/'assets/animations/manifest.json').read_text())
    w,h=manifest['grid']['cell_width'],manifest['grid']['cell_height']
    lines=['-- Generated by tools/import_assistant_clippy.py from the Clippit extraction.','return {']
    for clip in manifest['animations']:
        name=clip['name']
        strip=Image.open(a.source/'assets/animations/strips'/clip['strip_file']).convert('RGBA')
        count=clip['frame_count'];cols=min(8,count);rows=(count+cols-1)//cols
        sheet=Image.new('RGBA',(cols*w,rows*h))
        for i in range(count):sheet.alpha_composite(strip.crop((i*w,0,(i+1)*w,h)),((i%cols)*w,(i//cols)*h))
        encoded=io.BytesIO()
        sheet.save(encoded,format='PNG',optimize=True)
        destination=output/(name+'.png')
        temporary=destination.with_suffix('.tmp')
        temporary.write_bytes(encoded.getvalue())
        os.replace(temporary,destination)
        interval=max(16,round(clip['duration_ms']/count))
        loop=name.startswith('IDLE') or name=='RESTPOSE'
        lines.append(f'  ["{name}"]={{path="assets/clippy/{name}.png",columns={cols},rows={rows},count={count},interval={interval},loop={str(loop).lower()}}},')
    lines.append('}')
    (target/'animations.lua').write_text('\n'.join(lines)+'\n')
    print(f'Imported {len(manifest["animations"])} clips at {w}x{h}.')

if __name__=='__main__':main()
